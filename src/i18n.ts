export function translate(lang: Lang, key: Key): string {
  if (lang === 'ru') return ru[key] ?? uz[key];
  if (lang === 'en') return en[key] ?? uz[key];
  if (lang === 'uz-cyrl') return toCyrillic(uz[key]);
  return uz[key];
}

export function useT() {
  const [lang] = useLocal<Lang>('lang', 'uz');
  const t = (key: Key) => translate(lang, key);
  return { t, lang };
}
